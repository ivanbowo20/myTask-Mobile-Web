/** @type {import('next').NextConfig} */
const isProd = process.env.NODE_ENV === "production";

const nextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  compress: true,
  experimental: {
    optimizePackageImports: ["lucide-react", "framer-motion"],
  },
  async headers() {
    const securityHeaders = [
      {
        // Security & Egress protection headers
        source: "/:path*",
        headers: [
          {
            key: "X-Content-Type-Options",
            value: "nosniff",
          },
          {
            key: "X-Frame-Options",
            value: "DENY",
          },
          {
            key: "Referrer-Policy",
            value: "strict-origin-when-cross-origin",
          },
        ],
      },
    ];

    // Di development, JANGAN pasang cache 1 tahun agar chunk JS tidak desinkronisasi!
    if (!isProd) {
      return securityHeaders;
    }

    // Di production, aktifkan cache jangka panjang untuk performa optimal
    return [
      {
        // Cache aset statis & gambar hingga 1 tahun di browser dan CDN
        source: "/:all*(svg|jpg|jpeg|png|webp|ico|woff|woff2)",
        headers: [
          {
            key: "Cache-Control",
            value: "public, max-age=31536000, immutable",
          },
        ],
      },
      {
        // Cache Next.js built static chunks (JS & CSS)
        source: "/_next/static/:path*",
        headers: [
          {
            key: "Cache-Control",
            value: "public, max-age=31536000, immutable",
          },
        ],
      },
      ...securityHeaders,
    ];
  },
};

module.exports = nextConfig;
