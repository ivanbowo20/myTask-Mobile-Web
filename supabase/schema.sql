-- ------------------------------------------------------------------------------
-- 1. BETTER AUTH TABLES (Authentication & Session Security)
-- ------------------------------------------------------------------------------

-- Tabel User (Akun Utama - Email/Password & Google OAuth)
create table if not exists public."user" (
  id text primary key,
  name text not null,
  email text not null unique,
  "emailVerified" boolean not null default false,
  image text,
  "createdAt" timestamp with time zone not null default now(),
  "updatedAt" timestamp with time zone not null default now()
);

-- Tabel Session (Manajemen Sesi Login Aktif)
create table if not exists public."session" (
  id text primary key,
  "expiresAt" timestamp with time zone not null,
  token text not null unique,
  "createdAt" timestamp with time zone not null default now(),
  "updatedAt" timestamp with time zone not null default now(),
  "ipAddress" text,
  "userAgent" text,
  "userId" text not null references public."user"(id) on delete cascade
);

-- Tabel Account (Provider Google OAuth & Kredensial)
create table if not exists public."account" (
  id text primary key,
  "accountId" text not null,
  "providerId" text not null,
  "userId" text not null references public."user"(id) on delete cascade,
  "accessToken" text,
  "refreshToken" text,
  "idToken" text,
  "accessTokenExpiresAt" timestamp with time zone,
  "refreshTokenExpiresAt" timestamp with time zone,
  scope text,
  password text,
  "createdAt" timestamp with time zone not null default now(),
  "updatedAt" timestamp with time zone not null default now()
);

-- Tabel Verification (Token Keamanan & Verifikasi Email)
create table if not exists public."verification" (
  id text primary key,
  identifier text not null,
  value text not null,
  "expiresAt" timestamp with time zone not null,
  "createdAt" timestamp with time zone default now(),
  "updatedAt" timestamp with time zone default now()
);

-- ------------------------------------------------------------------------------
-- 2. APPLICATION PROFILES & PREFERENCES
-- ------------------------------------------------------------------------------

-- Tabel Profiles (Ekstensi Profil & Preferensi Tema Pengguna)
create table if not exists public.profiles (
  id text primary key references public."user"(id) on delete cascade,
  full_name text,
  email text,
  avatar_url text,
  bio text default '',
  theme_preference text not null default 'selenium',
  reminder_enabled boolean not null default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ------------------------------------------------------------------------------
-- 3. TASKFLOW CORE DATA TABLES
-- ------------------------------------------------------------------------------

-- Tabel Kategori (Categories)
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id text not null references public."user"(id) on delete cascade,
  nama text not null,
  warna text not null default '#38BDF8',
  icon text not null default 'Briefcase',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tabel Tugas Utama (Tasks)
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id text not null references public."user"(id) on delete cascade,
  kategori_id bigint references public.categories(id) on delete set null,
  judul text not null,
  deskripsi text default '',
  deadline timestamp with time zone,
  prioritas boolean not null default false,
  selesai boolean not null default false,
  reminder text default null,
  reminder_sent boolean not null default false,
  deadline_sent boolean not null default false,
  dibuat_pada timestamp with time zone default timezone('utc'::text, now()) not null,
  selesai_pada timestamp with time zone default null
);

-- Tabel Sub-Tugas (Subtasks / Checklist)
create table if not exists public.subtasks (
  id bigint generated by default as identity primary key,
  task_id bigint references public.tasks(id) on delete cascade not null,
  user_id text not null references public."user"(id) on delete cascade,
  judul text not null,
  selesai boolean not null default false,
  urutan integer not null default 0,
  dibuat_pada timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tabel Push Subscriptions (Web Push PWA)
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id text not null references public."user"(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
create index if not exists idx_push_subs_user on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;

-- Tabel Notifikasi (Notifications & Reminder Logs)
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id text not null references public."user"(id) on delete cascade,
  task_id bigint references public.tasks(id) on delete set null,
  tipe text not null default 'reminder',
  judul text not null,
  pesan text default '',
  dibaca boolean not null default false,
  dibuat_pada timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ------------------------------------------------------------------------------
-- 4. INDEXING PERFORMA TINGGI
-- ------------------------------------------------------------------------------
create index if not exists idx_user_email on public."user"(email);
create index if not exists idx_session_token on public."session"(token);
create index if not exists idx_session_user on public."session"("userId");
create index if not exists idx_account_user on public."account"("userId");
create index if not exists idx_categories_user on public.categories(user_id);
create unique index if not exists idx_categories_user_nama on public.categories(user_id, lower(nama));
create index if not exists idx_tasks_user on public.tasks(user_id);
create index if not exists idx_tasks_user_dibuat on public.tasks(user_id, dibuat_pada desc);
create index if not exists idx_tasks_kategori on public.tasks(kategori_id);
create index if not exists idx_tasks_deadline on public.tasks(deadline);
create index if not exists idx_tasks_selesai_purge on public.tasks(selesai, selesai_pada) where selesai = true;
create index if not exists idx_subtasks_task on public.subtasks(task_id);
create index if not exists idx_notifications_user on public.notifications(user_id);

