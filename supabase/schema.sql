-- ------------------------------------------------------------------------------
-- 6. AUTOMATION & CLEANUP FUNCTIONS (Zero-Cost Free Tier Maintenance)
-- ------------------------------------------------------------------------------
create or replace function public.purge_old_completed_tasks()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  deleted_count integer;
begin
  delete from public.tasks
  where selesai = true
    and selesai_pada is not null
    and selesai_pada < (now() - interval '14 days');
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

revoke all on function public.purge_old_completed_tasks() from public, anon, authenticated;
grant execute on function public.purge_old_completed_tasks() to service_role;

-- Fungsi RPC keep-alive ringan & aman (bisa dipanggil oleh anon untuk mereset idle timer 7 hari Supabase)
create or replace function public.ping()
returns jsonb
language sql
security definer
as $$
  select jsonb_build_object(
    'status', 'ok',
    'timestamp', now(),
    'message', 'pong'
  );
$$;

grant execute on function public.ping() to anon, authenticated, service_role;


