/**
 * Script Migrasi Tabel Khusus Kategori Notebook
 * Membuat tabel public.notebook_categories dan menghubungkan foreign key di public.notebooks.
 * 
 * Jalankan: node scripts/migrate-notebook-categories-table.js
 */

const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

function loadLocalEnv() {
  const envPath = path.resolve(process.cwd(), '.env.local');
  if (!fs.existsSync(envPath)) return;

  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  });
}

function getConnectionString() {
  const rawUrl = process.env.DATABASE_URL;
  if (!rawUrl) return null;

  try {
    const parsed = new URL(rawUrl);
    const match = parsed.hostname.match(/^db\.([a-z0-9]+)\.supabase\.co$/);
    if (match) {
      const projectRef = match[1];
      const poolerRegion = process.env.DATABASE_POOLER_HOST || 'aws-0-ap-southeast-1.pooler.supabase.com';
      return `postgresql://postgres.${projectRef}:${encodeURIComponent(parsed.password || '')}@${poolerRegion}:6543/postgres`;
    }
  } catch (err) {
    // Gunakan rawUrl jika parsing pooler gagal
  }
  return rawUrl;
}

const MIGRATION_SQL = `
-- 1. Buat Tabel public.notebook_categories
CREATE TABLE IF NOT EXISTS public.notebook_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES public."user"(id) ON DELETE CASCADE,
  nama text NOT NULL,
  warna text NOT NULL DEFAULT '#0284C7',
  icon text NOT NULL DEFAULT 'FolderSimple',
  dibuat_pada timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  CONSTRAINT uq_notebook_categories_user_nama UNIQUE (user_id, nama)
);

-- 2. Indexing Performa Tinggi
CREATE INDEX IF NOT EXISTS idx_notebook_categories_user ON public.notebook_categories (user_id);
CREATE INDEX IF NOT EXISTS idx_notebook_categories_user_nama ON public.notebook_categories (user_id, nama);

-- 3. Row Level Security (RLS)
ALTER TABLE public.notebook_categories ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.notebook_categories FROM anon, authenticated;

-- 4. Tambah kolom kategori_id pada public.notebooks jika belum ada
ALTER TABLE public.notebooks
ADD COLUMN IF NOT EXISTS kategori_id bigint REFERENCES public.notebook_categories(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_notebooks_kategori_id ON public.notebooks (kategori_id);
`;

async function runMigration() {
  loadLocalEnv();

  const connectionString = getConnectionString();
  if (!connectionString) {
    console.error('ERROR: DATABASE_URL tidak ditemukan di .env.local');
    process.exit(1);
  }

  console.log('Menghubungkan ke PostgreSQL Supabase...');
  const client = new Client({
    connectionString,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 10000,
  });

  try {
    await client.connect();
    console.log('Terhubung ke database.');

    console.log('Menjalankan migrasi tabel notebook_categories...');
    await client.query(MIGRATION_SQL);
    console.log('Migrasi tabel berhasil!');

    // Verifikasi tabel dan kolom
    const tableRes = await client.query(`
      SELECT table_name
      FROM information_schema.tables 
      WHERE table_schema = 'public' AND table_name = 'notebook_categories';
    `);

    const colRes = await client.query(`
      SELECT column_name, data_type 
      FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'notebooks' AND column_name = 'kategori_id';
    `);

    if (tableRes.rows.length > 0 && colRes.rows.length > 0) {
      console.log('VERIFIKASI SUKSES:');
      console.log('1. Tabel "notebook_categories": TERBUKTI ADA.');
      console.log('2. Kolom "notebooks.kategori_id": TERBUKTI ADA.');
    } else {
      console.warn('Peringatan: Verifikasi parsial gagal.');
    }

  } catch (err) {
    console.error('Gagal menjalankan migrasi:', err);
    process.exit(1);
  } finally {
    await client.end();
  }
}

runMigration();
