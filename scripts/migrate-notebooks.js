/**
 * Script Migrasi Khusus Fitur Notebooks
 * Menambahkan tabel notebooks, indeks, realtime publication, dan RLS ke PostgreSQL Supabase.
 *
 * Jalankan: node scripts/migrate-notebooks.js
 */

const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

function loadLocalEnv() {
  const envPath = path.resolve(process.cwd(), '.env.local');
  if (!fs.existsSync(envPath)) return;

  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  });
}

function getConnectionString() {
  const rawUrl = process.env.DATABASE_URL;
  if (!rawUrl) return null;

  try {
    const parsed = new URL(rawUrl);
    const match = parsed.hostname.match(/^db\.([a-z0-9]+)\.supabase\.co$/);
    if (match) {
      const projectRef = match[1];
      const poolerRegion = process.env.DATABASE_POOLER_HOST || 'aws-0-ap-southeast-1.pooler.supabase.com';
      return `postgresql://postgres.${projectRef}:${encodeURIComponent(parsed.password || '')}@${poolerRegion}:6543/postgres`;
    }
  } catch (err) {
    // Abaikan jika parsing gagal, gunakan rawUrl
  }
  return rawUrl;
}

const MIGRATION_SQL = `
-- 1. Buat Tabel Notebooks
create table if not exists public.notebooks (
  id bigint generated by default as identity primary key,
  user_id text not null references public."user"(id) on delete cascade,
  judul text not null,
  konten text default '',
  penting boolean not null default false,
  warna text not null default '#D97706',
  dibuat_pada timestamp with time zone default timezone('utc'::text, now()) not null,
  diperbarui_pada timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Indexing Performa Tinggi
create index if not exists idx_notebooks_user on public.notebooks(user_id);
create index if not exists idx_notebooks_user_dibuat on public.notebooks(user_id, dibuat_pada desc);
create index if not exists idx_notebooks_user_penting on public.notebooks(user_id, penting desc, diperbarui_pada desc);

-- 3. Row Level Security (RLS)
alter table public.notebooks enable row level security;
revoke all on public.notebooks from anon, authenticated;

-- 4. Realtime Publication
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'notebooks') then
    alter publication supabase_realtime add table public.notebooks;
  end if;
exception
  when others then
    -- Ignore if realtime publication does not exist
    null;
end $$;
`;

async function runMigration() {
  loadLocalEnv();

  const connectionString = getConnectionString();
  if (!connectionString) {
    console.error('❌ Error: DATABASE_URL tidak ditemukan di .env.local!');
    process.exit(1);
  }

  console.log('🔌 Menghubungkan ke PostgreSQL Supabase...');
  const client = new Client({
    connectionString,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 10000,
  });

  try {
    await client.connect();
    console.log('✅ Berhasil terhubung ke database!\n');

    console.log('🚀 Menjalankan DDL migrasi tabel notebooks...');
    await client.query(MIGRATION_SQL);
    console.log('✅ Tabel public.notebooks berhasil dibuat dan dikonfigurasi!');

    // Verifikasi keberadaan tabel dan kolom
    const cols = await client.query(`
      SELECT column_name, data_type, is_nullable
      FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'notebooks'
      ORDER BY ordinal_position;
    `);

    console.log('\n📋 Struktur Kolom Tabel notebooks:');
    cols.rows.forEach((c) => {
      console.log(`   - ${c.column_name.padEnd(16)}: ${c.data_type} (nullable: ${c.is_nullable})`);
    });

    // Verifikasi RLS
    const rls = await client.query(`
      SELECT tablename, rowsecurity
      FROM pg_tables
      WHERE schemaname = 'public' AND tablename = 'notebooks';
    `);
    const rlsActive = rls.rows[0]?.rowsecurity;
    console.log(`\n🔒 RLS notebooks: ${rlsActive ? 'ENABLED (Aktif & Aman)' : 'DISABLED'}`);

    console.log('\n🎉 [SUKSES] Migrasi notebooks selesai 100%!\n');
  } catch (err) {
    console.error('❌ Gagal mengeksekusi migrasi notebooks:', err);
    process.exit(1);
  } finally {
    await client.end();
  }
}

runMigration();
